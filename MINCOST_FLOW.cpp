#include <bits/stdc++.h>
using namespace std;

using ll = long long;
using pii = pair<int, int>;
using pli = pair<ll, int>;
using pll = pair<ll, ll>;

#define fi first
#define se second
#define NAME ""

const ll INF = 1e18 + 7;
const int N = 105;
const int MOD = 1e9 + 7;

struct edge
{
    int from, to, flow, capa;
    ll cost;
};

int n, m, k, S, T, par[N];
vector<edge> E;
vector<int> g[N];

bool BFS()
{
    vector<ll> d(n + 1, INF);
    memset(par, -1, sizeof(par));
    vector<bool> inq(n + 1, false);
    queue<int> q;

    d[S] = 0;
    q.push(S); inq[S] = true;

    while (!q.empty())
    {
        int u = q.front(); q.pop();
        inq[u] = false;
        for (int id : g[u])
        {
            int v = E[id].to, cost = E[id].cost, flow = E[id].flow, capa = E[id].capa;
            if (capa - flow > 0 && d[v] > d[u] + cost)
            {
                d[v] = d[u] + cost;
                par[v] = id;
                if (inq[v] == false)
                {
                    inq[v] = true;
                    q.push(v);
                }
            }
        }
    }

    return (par[T] != -1);
}

void SOLVE()
{
    int totalFlow = 0;
    ll totalCost = 0;
    while (totalFlow < k)
    {
        if (BFS() == false) break;

        int u = T;
        int newFlow = k - totalFlow;

        while (u != S)
        {
            int id = par[u];
            newFlow = min(newFlow, E[id].capa - E[id].flow);
            u = E[id].from;
        }

        u = T;
        while (u != S)
        {
            int id = par[u];
            E[id].flow += newFlow;
            E[id ^ 1].flow -= newFlow;
            u = E[id].from;
            totalCost += E[id].cost * newFlow;
        }

        totalFlow += newFlow;
    }

    if (totalFlow != k)
    {
        cout << "-1 \n";
        return;
    }

    cout << totalCost << "\n";
    for (auto it : E)
        if (it.flow > 0) cout << it.from << " " << it.to << " " << it.flow << "\n";
    cout << "0 0 0 \n";
}

int main()
{
    ios::sync_with_stdio(0);
    cin.tie(0); cout.tie(0);
    
    if (fopen(NAME ".INP", "r"))
    {
        freopen(NAME ".INP", "r", stdin);
        freopen(NAME ".OUT", "w", stdout);
    }

    cin >> n >> m >> k >> S >> T;

    int id = 0;
    for (int i = 1; i <= m; i++)
    {
        int u, v, capa; ll cost;
        cin >> u >> v >> cost >> capa;
        E.push_back({u, v, 0, capa, cost});
        g[u].push_back(id++);
        E.push_back({v, u, 0, 0, -cost});
        g[v].push_back(id++);
        E.push_back({v, u, 0, capa, cost});
        g[v].push_back(id++);
        E.push_back({u, v, 0, 0, -cost});
        g[u].push_back(id++);
    }

    SOLVE();
    return 0;
}
